import 'package:flutter/material.dart';

import 'pixel_ui.dart';

const _glyphWidth = 5;
const _glyphHeight = 7;

/// 用 5×7 點陣畫出來的像素字。支援數字、英文字母（不分大小寫）和常用符號；
/// 中文請用一般的 [Text]。
class PixelText extends StatelessWidget {
  const PixelText(
    this.text, {
    super.key,
    this.dot = 3,
    this.color = PixelColors.ink,
  });

  final String text;

  /// 每一個點的大小（邏輯像素）。字高 = 7 × [dot]。
  final double dot;
  final Color color;

  @override
  Widget build(BuildContext context) {
    final length = text.length;
    final columns = length == 0 ? 0 : length * (_glyphWidth + 1) - 1;
    return Semantics(
      label: text,
      child: CustomPaint(
        size: Size(columns * dot, _glyphHeight * dot),
        painter: _PixelTextPainter(text.toUpperCase(), dot, color),
      ),
    );
  }
}

class _PixelTextPainter extends CustomPainter {
  _PixelTextPainter(this.text, this.dot, this.color);

  final String text;
  final double dot;
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final paint = Paint()
      ..color = color
      ..isAntiAlias = false;
    for (var i = 0; i < text.length; i++) {
      final rows = _glyphs[text[i]] ?? _glyphs[' ']!;
      final left = i * (_glyphWidth + 1) * dot;
      for (var y = 0; y < rows.length; y++) {
        final row = rows[y];
        var x = 0;
        while (x < row.length) {
          if (row[x] != '#') {
            x++;
            continue;
          }
          // 同一列連續的點合併成一個矩形，畫起來比較快也不會有縫。
          final start = x;
          while (x < row.length && row[x] == '#') {
            x++;
          }
          canvas.drawRect(
            Rect.fromLTWH(left + start * dot, y * dot, (x - start) * dot, dot),
            paint,
          );
        }
      }
    }
  }

  @override
  bool shouldRepaint(_PixelTextPainter old) =>
      old.text != text || old.dot != dot || old.color != color;
}

